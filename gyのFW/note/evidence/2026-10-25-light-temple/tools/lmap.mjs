import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parseLevel } from "../packages/shared/src/level2.ts";
const dir = "data/tutorials/levels";
const json = JSON.parse(readFileSync(join(dir, "light_01.json"), "utf8"));
const L = parseLevel("light_01", json, (source) => JSON.parse(readFileSync(join(dir, source), "utf8")));
console.log("== 教学 =="); 
for (const step of L.tutorials) for (const t of step.textItems) console.log(` [${t.x},${t.y}] ${t.text}`);
console.log("== spawn/door ==");
console.log("fb spawn", L.spawn.fireboy, "wg spawn", L.spawn.watergirl);
console.log("fb door", L.doors.fireboy, "wg door", L.doors.watergirl);
console.log("== Objects（全部，屏幕 px 中心近似）==");
for (const m of L.platforms) console.log("platform", m.id, JSON.stringify({ x: m.x, y: m.y, w: m.w, h: m.h, dx: m.dx, dy: m.dy, group: m.group }));
for (const m of L.levers) console.log("lever", m.id, JSON.stringify({ x: m.x, y: m.y, group: m.group, onis: m.onis, startPos: m.startPos }));
for (const m of L.pushers) console.log("pusher", m.id, JSON.stringify({ x: m.x, y: m.y, group: m.group }));
for (const m of L.beamers) console.log("beamer", m.id, JSON.stringify({ x: m.x, y: m.y, rot: m.rotation, color: m.color, group: m.group, init: m.initialState }));
for (const m of L.rotMirrors) console.log("rotmirror", m.id, JSON.stringify({ x: m.x, y: m.y, rot: m.rotation, group: m.group, dir: m.dir }));
for (const m of L.boxMirrors) console.log("boxmirror", m.id, JSON.stringify({ x: m.x, y: m.y, rot: m.rotation, size: m.boxSize }));
for (const m of L.infiniteMirrors) console.log("infinitemirror", m.id, JSON.stringify({ x: m.x, y: m.y, rot: m.rotation, group: m.group }));
for (const m of L.lightPushers) console.log("lightpusher", m.id, JSON.stringify({ x: m.x, y: m.y, rot: m.rotation, group: m.group, color: m.color }));
for (const m of L.sliders) console.log("slider", m.id, JSON.stringify({ x: m.x, y: m.y, group: m.group, max: m.max, w: m.widthPx }));
for (const m of L.hangings) console.log("hanging", m.id, JSON.stringify(m.pts));
for (const m of L.pulleys) console.log("pulley", m.id, JSON.stringify(m.pts));
for (const m of L.romans) console.log("roman", m.id, JSON.stringify(m.pts));
console.log("== liquids ==", JSON.stringify(L.liquidRuns));
console.log("== diamonds ==");
for (const d of L.diamonds) console.log(" diamond", d.char, JSON.stringify({ x: d.x, y: d.y }));
